#!/usr/bin/env python3
"""Generate src/font_data.h (14x28 antialiased ASCII font from DejaVu Sans Mono)
and sce_sys/icon0.png (512x512 neon icon). Outputs are committed; rerun only to change them."""
from PIL import Image, ImageDraw, ImageFont, ImageFilter, ImageChops

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
CW, CH, SIZE, BASE = 14, 28, 23, 22

def gen_font(path):
    f = ImageFont.truetype(FONT, SIZE)
    out = ["/* generated by tools/genassets.py - do not edit */",
           "#define FONT_W %d" % CW, "#define FONT_H %d" % CH,
           "static const unsigned char font_data[95][FONT_W*FONT_H] = {"]
    for c in range(32, 127):
        im = Image.new("L", (CW, CH), 0)
        ImageDraw.Draw(im).text((0, BASE), chr(c), font=f, fill=255, anchor="ls")
        out.append("{" + ",".join(str(v) for v in im.tobytes()) + "},")
    out.append("};")
    open(path, "w").write("\n".join(out) + "\n")

def gen_icon(path):
    n = 512
    bg = Image.new("RGB", (n, n), (4, 8, 24))
    glow = Image.new("RGB", (n, n), (0, 0, 0))
    d = ImageDraw.Draw(glow)
    d.rounded_rectangle((70, 70, 442, 442), 48, outline=(0, 170, 255), width=14)
    d.polygon([(256, 150), (356, 290), (156, 290)], fill=(0, 200, 255))
    d.rectangle((226, 290, 286, 372), fill=(0, 200, 255))
    glow = glow.filter(ImageFilter.GaussianBlur(14))
    img = ImageChops.add(bg, glow)
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((70, 70, 442, 442), 48, outline=(120, 225, 255), width=6)
    d.polygon([(256, 150), (356, 290), (156, 290)], fill=(150, 235, 255))
    d.rectangle((226, 290, 286, 372), fill=(150, 235, 255))
    img.save(path)

gen_font("src/font_data.h")
gen_icon("sce_sys/icon0.png")
print("ok")
